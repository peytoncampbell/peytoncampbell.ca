import { useCallback, useEffect, useRef, useState } from 'react';
import { AUTH_CONFIGURED, SUPABASE_ANON_KEY, SUPABASE_URL } from './ownerAuth';
import OddsInventory from './OddsInventory';
import { loadNativeBoard } from './oddsInventoryData';

/**
 * The odds board: the scanner's own report, as published.
 *
 * The published artifact is a complete, self-contained HTML document carrying its own styles, its
 * own tab switching and its own freshness clock. So it is rendered in an iframe rather than
 * reimplemented as React components: one source of truth for the layout, and a change to the
 * scanner ships without touching this file.
 *
 * `sandbox="allow-scripts"` WITHOUT `allow-same-origin` gives the frame an opaque origin. Its inline
 * clock still runs, and it cannot reach this page's DOM, cookies or localStorage - which matters
 * because the report is generated by a script and rendered as markup.
 *
 * Reads pc_odds with the ANON key, which is public by design: the table is world-readable for now.
 * When the board is gated, swap loadRow() for ownerFetch + ensureFresh and add useNoIndex(); the
 * SQL that goes with it is in oddsjam-lite/supabase/migrations/20261008120000_peyton_odds_board.sql.
 */

type State =
  | { kind: 'loading' }
  | { kind: 'unconfigured' }
  | { kind: 'empty' }
  | { kind: 'error'; message: string }
  | { kind: 'ready'; html: string; generatedAt: string };

const AUTO_UPDATE_MS = 5 * 60 * 1000;
const EXPIRY_RETRY_MS = 15000;

async function loadRow(signal: AbortSignal, expectedJobId?: string): Promise<State> {
  if (!AUTH_CONFIGURED) return { kind: 'unconfigured' };
  try {
    // Automatic publications never replace a PIN job's UUID-bound result.
    const continuous = expectedJobId ? Promise.resolve(null) : fetch(
      `${SUPABASE_URL}/rest/v1/pc_odds_continuous_board?select=job_id,generated_at,html&id=eq.1&limit=1`,
      { headers: { apikey: SUPABASE_ANON_KEY as string, Authorization: `Bearer ${SUPABASE_ANON_KEY}` },
        cache: 'no-store', signal },
    ).then(async response => {
      if (!response.ok) return null;
      const rows = await response.json() as Array<{ job_id: string; generated_at: string; html: string }>;
      const row = Array.isArray(rows) ? rows[0] : null;
      return row && typeof row.html === 'string' && Number.isFinite(Date.parse(row.generated_at)) &&
        row.html.includes('<meta name="odds-continuous" content="1">') &&
        row.html.includes(`<meta name="odds-fast-refresh" content="${row.job_id}">`) ? row : null;
    }).catch(() => null);
    const fast = await fetch(
      `${SUPABASE_URL}/rest/v1/pc_odds_fast_board?select=job_id,generated_at,html&id=eq.1&limit=1`,
      { headers: { apikey: SUPABASE_ANON_KEY as string, Authorization: `Bearer ${SUPABASE_ANON_KEY}` },
        cache: 'no-store', signal },
    );
    if (!fast.ok) throw new Error(`Price board HTTP ${fast.status}`);
    const fastRows = await fast.json() as Array<{ job_id: string; generated_at: string; html: string }>;
    if (!Array.isArray(fastRows)) throw new Error('Invalid price board response.');
    const live = await continuous;
    if (live && (!fastRows.length || Date.parse(live.generated_at) > Date.parse(fastRows[0].generated_at))) {
      return { kind: 'ready', html: live.html, generatedAt: live.generated_at };
    }
    if (fastRows.length) {
      if (expectedJobId && fastRows[0].job_id !== expectedJobId) throw new Error('Published board belongs to a different refresh.');
      if (typeof fastRows[0].html !== 'string' || !fastRows[0].html.includes('<meta name="odds-fast-refresh"')) {
        throw new Error('Invalid price board identity.');
      }
      return { kind: 'ready', html: fastRows[0].html, generatedAt: fastRows[0].generated_at };
    }
    if (expectedJobId) throw new Error('This refresh has no published price board.');
    const native = await loadNativeBoard(signal);
    if (native) return { kind: 'ready', html: native.html, generatedAt: native.generatedAt };
    const res = await fetch(
      `${SUPABASE_URL}/rest/v1/pc_odds?select=generated_at,html&id=eq.1&limit=1`,
      {
        headers: {
          apikey: SUPABASE_ANON_KEY as string,
          Authorization: `Bearer ${SUPABASE_ANON_KEY}`,
        },
        cache: 'no-store',
        signal,
      },
    );
    if (!res.ok) return { kind: 'error', message: `HTTP ${res.status}` };
    const rows = (await res.json()) as Array<{ generated_at: string; html: string }>;
    // A gated table answers an anonymous caller with a valid, EMPTY result rather than an error,
    // so "no row" must be its own state and must never read as a failure.
    if (!Array.isArray(rows) || rows.length === 0) return { kind: 'empty' };
    return { kind: 'ready', html: rows[0].html, generatedAt: rows[0].generated_at };
  } catch (e) {
    return { kind: 'error', message: e instanceof Error ? e.message : 'network error' };
  }
}

export default function Odds({ onHome }: { onHome: () => void }) {
  const [state, setState] = useState<State>({ kind: 'loading' });
  const mounted = useRef(true);
  const boardLoad = useRef<{ generation: number; controller: AbortController | null }>({ generation: 0, controller: null });
  const [view, setView] = useState<'markets' | 'coverage' | 'board'>('board');
  const [inventoryAutoRevision, setInventoryAutoRevision] = useState(0);

  const load = useCallback((budgetMs = 10000, expectedJobId?: string, background = false) => {
    boardLoad.current.controller?.abort();
    const controller = new AbortController();
    const generation = ++boardLoad.current.generation;
    boardLoad.current.controller = controller;
    if (!background) setState({ kind: 'loading' });
    const timer = setTimeout(() => {
      controller.abort();
      if (!background && mounted.current && generation === boardLoad.current.generation) {
        setState({ kind: 'error', message: 'Could not load the price board in time. Automatic updates will retry.' });
      }
    }, Math.max(0, budgetMs));
    void loadRow(controller.signal, expectedJobId).then(result => {
      if (mounted.current && !controller.signal.aborted && generation === boardLoad.current.generation) {
        setState(previous => {
          if (background && result.kind !== 'ready') return previous;
          if (background && previous.kind === 'ready' && result.kind === 'ready' &&
              Date.parse(result.generatedAt) <= Date.parse(previous.generatedAt)) return previous;
          return result;
        });
      }
    }).finally(() => clearTimeout(timer));
  }, []);

  useEffect(() => { load(); }, [load]);
  useEffect(() => {
    const update = () => {
      if (typeof document !== 'undefined' && document.visibilityState === 'hidden') return;
      load(10000, undefined, true);
      setInventoryAutoRevision(value => value + 1);
    };
    const timer = setInterval(update, AUTO_UPDATE_MS);
    const onVisible = () => { if (document.visibilityState === 'visible') update(); };
    if (typeof document !== 'undefined') document.addEventListener('visibilitychange', onVisible);
    return () => {
      clearInterval(timer);
      if (typeof document !== 'undefined') document.removeEventListener('visibilitychange', onVisible);
    };
  }, [load]);
  useEffect(() => {
    if (view !== 'board' || state.kind !== 'ready') return;
    const expiry = Number(state.html.match(/(?:[,;])\s*(?:END|DIRECT_END)\s*=\s*([0-9]+(?:\.[0-9]+)?)/)?.[1]);
    if (!Number.isFinite(expiry) || expiry <= 0) return;
    const update = () => {
      if (typeof document === 'undefined' || document.visibilityState !== 'hidden') load(10000, undefined, true);
    };
    let retry: ReturnType<typeof setInterval> | undefined;
    const timer = setTimeout(() => {
      update();
      // Retain the original expiry and retry if the source has no newer board.
      retry = setInterval(update, EXPIRY_RETRY_MS);
    }, Math.max(EXPIRY_RETRY_MS, Math.min(AUTO_UPDATE_MS, expiry * 1000 - Date.now() - EXPIRY_RETRY_MS)));
    return () => { clearTimeout(timer); if (retry !== undefined) clearInterval(retry); };
  }, [view, state, load]);
  useEffect(() => {
    mounted.current = true;
    return () => { mounted.current = false; boardLoad.current.controller?.abort(); };
  }, []);
  return (
    <div className="fixed inset-0 flex flex-col bg-[#f5f5f7] text-[#1d1d1f]" style={{ fontFamily: '-apple-system, BlinkMacSystemFont, "Segoe UI", sans-serif' }}>
      <header className="flex-none border-b border-[#e5e5ea] bg-white/80 backdrop-blur-xl">
      <div className="mx-auto flex h-16 w-full max-w-[1120px] items-center gap-3 px-4 sm:px-6">
        <button
          onClick={onHome}
          aria-label="Back to peytoncampbell.ca"
          className="flex min-h-10 items-center text-xs text-[#6e6e73] transition-colors hover:text-[#1d1d1f] focus-visible:outline-blue-500"
        >
          &larr; <span className="hidden sm:inline">peytoncampbell.ca</span>
        </button>
        <span className="text-lg font-semibold tracking-[-0.05em]">Odds<span className="text-[#0071e3]">.</span></span>
        <span className="ml-auto flex items-center gap-2 sm:gap-3">
          <span title="Checks every five minutes and before displayed prices expire" className="inline-flex items-center gap-1.5 rounded-full bg-[#edf8f0] px-3 py-1.5 text-[11px] font-medium text-[#157f47]">
            <span className="h-1.5 w-1.5 rounded-full bg-[#157f47]" />Auto · 5 min
          </span>
          {state.kind === 'ready' && view === 'board' && (
            <span className="hidden text-[11px] text-[#6e6e73] lg:inline">
              Published {new Date(state.generatedAt).toLocaleTimeString([], { hour: 'numeric', minute: '2-digit' })}
            </span>
          )}
        </span>
      </div>
      </header>

      <nav aria-label="Odds views" className="mx-auto flex w-full max-w-[1120px] flex-none gap-1 px-4 pt-4 sm:px-6">
        {([['board', 'EV & Arb'], ['markets', 'All markets'], ['coverage', 'Coverage']] as const).map(([key,label]) =>
          <button key={key} onClick={() => setView(key)} aria-current={view === key ? 'page' : undefined}
            className={`min-h-10 rounded-full px-4 text-xs font-medium transition-colors focus-visible:outline-blue-500 ${view === key ? 'bg-[#e4effd] text-[#0066c9]' : 'text-[#6e6e73] hover:bg-[#eaeaf0] hover:text-[#1d1d1f]'}`}>{label}</button>)}
      </nav>
      <main className="min-h-0 flex-1">
        {view !== 'board' ? <OddsInventory coverage={view === 'coverage'} revision={inventoryAutoRevision} /> : <>
        {state.kind === 'ready' ? (
          <iframe
            title="Odds board"
            srcDoc={state.html}
            sandbox="allow-scripts"
            className="h-full w-full border-0"
          />
        ) : (
          <div className="flex h-full items-center justify-center px-6">
            <p role={state.kind === 'error' ? 'alert' : 'status'} className="max-w-sm rounded-2xl border border-[#e5e5ea] bg-white px-8 py-7 text-center text-sm leading-relaxed text-[#6e6e73]">
              {state.kind === 'loading' && 'Loading the board…'}
              {state.kind === 'unconfigured' &&
                'This build is missing its Supabase URL or anon key, so the board cannot load.'}
              {state.kind === 'empty' &&
                'Nothing published yet. The scanner writes here after its next sweep.'}
              {state.kind === 'error' && `Could not reach the board (${state.message}).`}
            </p>
          </div>
        )}
        </>}
      </main>
    </div>
  );
}
