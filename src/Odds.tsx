import { useCallback, useEffect, useState } from 'react';
import { AUTH_CONFIGURED, SUPABASE_ANON_KEY, SUPABASE_URL } from './ownerAuth';

/**
 * The odds board: the scanner's own report, as published.
 *
 * The published artifact is a complete, self-contained HTML document carrying its own styles, its
 * own tab switching and its own freshness clock. So it is rendered in an iframe rather than
 * reimplemented as React components: one source of truth for the layout, and a change to the
 * scanner ships without touching this file.
 *
 * `sandbox="allow-scripts"` WITHOUT `allow-same-origin` gives the frame an opaque origin. Its inline
 * clock still runs, and it cannot reach this page's DOM, cookies or localStorage - which matters
 * because the report is generated by a script and rendered as markup.
 *
 * Reads pc_odds with the ANON key, which is public by design: the table is world-readable for now.
 * When the board is gated, swap loadRow() for ownerFetch + ensureFresh and add useNoIndex(); the
 * SQL that goes with it is in oddsjam-lite/supabase/migrations/20261008120000_peyton_odds_board.sql.
 */

type State =
  | { kind: 'loading' }
  | { kind: 'unconfigured' }
  | { kind: 'empty' }
  | { kind: 'error'; message: string }
  | { kind: 'ready'; html: string; generatedAt: string };

async function loadRow(): Promise<State> {
  if (!AUTH_CONFIGURED) return { kind: 'unconfigured' };
  try {
    const res = await fetch(
      `${SUPABASE_URL}/rest/v1/pc_odds?select=generated_at,html&id=eq.1&limit=1`,
      {
        headers: {
          apikey: SUPABASE_ANON_KEY as string,
          Authorization: `Bearer ${SUPABASE_ANON_KEY}`,
        },
        cache: 'no-store',
      },
    );
    if (!res.ok) return { kind: 'error', message: `HTTP ${res.status}` };
    const rows = (await res.json()) as Array<{ generated_at: string; html: string }>;
    // A gated table answers an anonymous caller with a valid, EMPTY result rather than an error,
    // so "no row" must be its own state and must never read as a failure.
    if (!Array.isArray(rows) || rows.length === 0) return { kind: 'empty' };
    return { kind: 'ready', html: rows[0].html, generatedAt: rows[0].generated_at };
  } catch (e) {
    return { kind: 'error', message: e instanceof Error ? e.message : 'network error' };
  }
}

export default function Odds({ onHome }: { onHome: () => void }) {
  const [state, setState] = useState<State>({ kind: 'loading' });

  const load = useCallback(() => {
    setState({ kind: 'loading' });
    void loadRow().then(setState);
  }, []);

  useEffect(() => { load(); }, [load]);

  return (
    <div className="fixed inset-0 flex flex-col bg-[#0f1115] text-white">
      <header className="flex h-12 flex-none items-center gap-3 border-b border-white/10 px-4">
        <button
          onClick={onHome}
          className="text-sm text-white/60 transition-colors hover:text-white"
        >
          &larr; peytoncampbell.ca
        </button>
        <span className="text-sm font-semibold tracking-wide text-white/90">Odds board</span>
        <span className="ml-auto flex items-center gap-3">
          {state.kind === 'ready' && (
            <span className="hidden text-xs text-white/40 sm:inline">
              published {new Date(state.generatedAt).toLocaleString()}
            </span>
          )}
          <button
            onClick={load}
            className="rounded-md bg-white/10 px-3 py-1 text-xs font-medium text-white/80 transition-colors hover:bg-white/20"
          >
            Reload
          </button>
        </span>
      </header>

      <main className="min-h-0 flex-1">
        {state.kind === 'ready' ? (
          <iframe
            title="Odds board"
            srcDoc={state.html}
            sandbox="allow-scripts"
            className="h-full w-full border-0"
          />
        ) : (
          <div className="flex h-full items-center justify-center px-6">
            <p className="max-w-sm text-center text-sm leading-relaxed text-white/50">
              {state.kind === 'loading' && 'Loading the board…'}
              {state.kind === 'unconfigured' &&
                'This build is missing its Supabase URL or anon key, so the board cannot load.'}
              {state.kind === 'empty' &&
                'Nothing published yet. The scanner writes here after its next sweep.'}
              {state.kind === 'error' && `Could not reach the board (${state.message}).`}
            </p>
          </div>
        )}
      </main>
    </div>
  );
}
