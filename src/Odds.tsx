import { useCallback, useEffect, useRef, useState } from 'react';
import { AUTH_CONFIGURED, SUPABASE_ANON_KEY, SUPABASE_URL } from './ownerAuth';
import { submitRefresh, watchRefresh, type RefreshStatus } from './oddsRefresh';
import OddsInventory from './OddsInventory';
import { loadNativeBoard } from './oddsInventoryData';

/**
 * The odds board: the scanner's own report, as published.
 *
 * The published artifact is a complete, self-contained HTML document carrying its own styles, its
 * own tab switching and its own freshness clock. So it is rendered in an iframe rather than
 * reimplemented as React components: one source of truth for the layout, and a change to the
 * scanner ships without touching this file.
 *
 * `sandbox="allow-scripts"` WITHOUT `allow-same-origin` gives the frame an opaque origin. Its inline
 * clock still runs, and it cannot reach this page's DOM, cookies or localStorage - which matters
 * because the report is generated by a script and rendered as markup.
 *
 * Reads pc_odds with the ANON key, which is public by design: the table is world-readable for now.
 * When the board is gated, swap loadRow() for ownerFetch + ensureFresh and add useNoIndex(); the
 * SQL that goes with it is in oddsjam-lite/supabase/migrations/20261008120000_peyton_odds_board.sql.
 */

type State =
  | { kind: 'loading' }
  | { kind: 'unconfigured' }
  | { kind: 'empty' }
  | { kind: 'error'; message: string }
  | { kind: 'ready'; html: string; generatedAt: string };

async function loadRow(signal: AbortSignal, expectedJobId?: string): Promise<State> {
  if (!AUTH_CONFIGURED) return { kind: 'unconfigured' };
  try {
    // Automatic publications never replace a PIN job's UUID-bound result.
    const continuous = expectedJobId ? Promise.resolve(null) : fetch(
      `${SUPABASE_URL}/rest/v1/pc_odds_continuous_board?select=job_id,generated_at,html&id=eq.1&limit=1`,
      { headers: { apikey: SUPABASE_ANON_KEY as string, Authorization: `Bearer ${SUPABASE_ANON_KEY}` },
        cache: 'no-store', signal },
    ).then(async response => {
      if (!response.ok) return null;
      const rows = await response.json() as Array<{ job_id: string; generated_at: string; html: string }>;
      const row = Array.isArray(rows) ? rows[0] : null;
      return row && typeof row.html === 'string' && Number.isFinite(Date.parse(row.generated_at)) &&
        row.html.includes('<meta name="odds-continuous" content="1">') &&
        row.html.includes(`<meta name="odds-fast-refresh" content="${row.job_id}">`) ? row : null;
    }).catch(() => null);
    const fast = await fetch(
      `${SUPABASE_URL}/rest/v1/pc_odds_fast_board?select=job_id,generated_at,html&id=eq.1&limit=1`,
      { headers: { apikey: SUPABASE_ANON_KEY as string, Authorization: `Bearer ${SUPABASE_ANON_KEY}` },
        cache: 'no-store', signal },
    );
    if (!fast.ok) throw new Error(`Price board HTTP ${fast.status}`);
    const fastRows = await fast.json() as Array<{ job_id: string; generated_at: string; html: string }>;
    if (!Array.isArray(fastRows)) throw new Error('Invalid price board response.');
    const live = await continuous;
    if (live && (!fastRows.length || Date.parse(live.generated_at) > Date.parse(fastRows[0].generated_at))) {
      return { kind: 'ready', html: live.html, generatedAt: live.generated_at };
    }
    if (fastRows.length) {
      if (expectedJobId && fastRows[0].job_id !== expectedJobId) throw new Error('Published board belongs to a different refresh.');
      if (typeof fastRows[0].html !== 'string' || !fastRows[0].html.includes('<meta name="odds-fast-refresh"')) {
        throw new Error('Invalid price board identity.');
      }
      return { kind: 'ready', html: fastRows[0].html, generatedAt: fastRows[0].generated_at };
    }
    if (expectedJobId) throw new Error('This refresh has no published price board.');
    const native = await loadNativeBoard(signal);
    if (native) return { kind: 'ready', html: native.html, generatedAt: native.generatedAt };
    const res = await fetch(
      `${SUPABASE_URL}/rest/v1/pc_odds?select=generated_at,html&id=eq.1&limit=1`,
      {
        headers: {
          apikey: SUPABASE_ANON_KEY as string,
          Authorization: `Bearer ${SUPABASE_ANON_KEY}`,
        },
        cache: 'no-store',
        signal,
      },
    );
    if (!res.ok) return { kind: 'error', message: `HTTP ${res.status}` };
    const rows = (await res.json()) as Array<{ generated_at: string; html: string }>;
    // A gated table answers an anonymous caller with a valid, EMPTY result rather than an error,
    // so "no row" must be its own state and must never read as a failure.
    if (!Array.isArray(rows) || rows.length === 0) return { kind: 'empty' };
    return { kind: 'ready', html: rows[0].html, generatedAt: rows[0].generated_at };
  } catch (e) {
    return { kind: 'error', message: e instanceof Error ? e.message : 'network error' };
  }
}

export default function Odds({ onHome }: { onHome: () => void }) {
  const [state, setState] = useState<State>({ kind: 'loading' });
  const [refreshOpen, setRefreshOpen] = useState(false);
  const [pin, setPin] = useState('');
  const [submitting, setSubmitting] = useState(false);
  const [refresh, setRefresh] = useState<RefreshStatus | null>(null);
  const [refreshError, setRefreshError] = useState('');
  const [jobId, setJobId] = useState<string | null>(null);
  const dialog = useRef<HTMLDialogElement>(null);
  const mounted = useRef(true);
  const refreshStarted = useRef(0);
  const boardLoad = useRef<{ generation: number; controller: AbortController | null }>({ generation: 0, controller: null });
  const busy = submitting || jobId !== null;
  const [view, setView] = useState<'markets' | 'coverage' | 'board'>('board');
  const [inventoryRevision, setInventoryRevision] = useState(0);

  const load = useCallback((budgetMs = 10000, expectedJobId?: string, background = false) => {
    boardLoad.current.controller?.abort();
    const controller = new AbortController();
    const generation = ++boardLoad.current.generation;
    boardLoad.current.controller = controller;
    if (!background) setState({ kind: 'loading' });
    const timer = setTimeout(() => {
      controller.abort();
      if (!background && mounted.current && generation === boardLoad.current.generation) {
        setState({ kind: 'error', message: 'The price board could not be displayed within the refresh deadline. Reload to check the acknowledged publication.' });
      }
    }, Math.max(0, budgetMs));
    void loadRow(controller.signal, expectedJobId).then(result => {
      if (mounted.current && !controller.signal.aborted && generation === boardLoad.current.generation) {
        setState(previous => {
          if (background && result.kind !== 'ready') return previous;
          if (background && previous.kind === 'ready' && result.kind === 'ready' &&
              Date.parse(result.generatedAt) <= Date.parse(previous.generatedAt)) return previous;
          return result;
        });
      }
    }).finally(() => clearTimeout(timer));
  }, []);

  useEffect(() => { load(); }, [load]);
  useEffect(() => {
    if (busy || refreshOpen || view !== 'board') return;
    const timer = setInterval(() => {
      if (typeof document !== 'undefined' && document.visibilityState === 'hidden') return;
      load(10000, undefined, true);
    }, 15000);
    return () => clearInterval(timer);
  }, [busy, refreshOpen, view, load]);
  useEffect(() => {
    mounted.current = true;
    return () => { mounted.current = false; boardLoad.current.controller?.abort(); };
  }, []);
  useEffect(() => {
    if (refreshOpen) dialog.current?.showModal();
    else dialog.current?.close();
  }, [refreshOpen]);
  useEffect(() => {
    if (!jobId) return;
    const controller = new AbortController();
    void watchRefresh(jobId, setRefresh, controller.signal, 70,
      Math.max(0, 60000 - (Date.now() - refreshStarted.current))).then(result => {
      if (controller.signal.aborted) return;
      setJobId(null);
      if (result.state === 'complete') {
        load(Math.max(0, 60000 - (Date.now() - refreshStarted.current)), result.job_id ?? undefined);
        setInventoryRevision(value => value + 1); setView('board');
      }
    }).catch(error => {
      if (controller.signal.aborted) return;
      setJobId(null);
      setRefreshError(error instanceof Error ? error.message : 'Could not check the refresh.');
    });
    return () => controller.abort();
  }, [jobId, load]);

  const requestRefresh = async (event: React.FormEvent) => {
    event.preventDefault();
    if (busy) return;
    setSubmitting(true);
    refreshStarted.current = Date.now();
    setRefreshError('');
    const submittedPin = pin;
    setPin('');
    try {
      const result = await submitRefresh(submittedPin);
      if (!mounted.current) return;
      setRefresh(result);
      if ((result.state === 'queued' || result.state === 'running') && result.job_id) {
        setJobId(result.job_id);
      }
    } catch (error) {
      if (mounted.current) setRefreshError(error instanceof Error ? error.message : 'Refresh request failed.');
    } finally {
      if (mounted.current) setSubmitting(false);
    }
  };

  return (
    <div className="fixed inset-0 flex flex-col bg-[#0f1115] text-white">
      <header className="flex h-12 flex-none items-center gap-3 border-b border-white/10 px-4">
        <button
          onClick={onHome}
          className="text-sm text-white/60 transition-colors hover:text-white"
        >
          &larr; <span className="hidden sm:inline">peytoncampbell.ca</span>
        </button>
        <span className="text-sm font-semibold tracking-wide text-white/90">Odds</span>
        <span className="ml-auto flex items-center gap-3">
          {state.kind === 'ready' && view === 'board' && (
            <span className="hidden text-xs text-white/40 sm:inline">
              Live · published {new Date(state.generatedAt).toLocaleString()}
            </span>
          )}
          <button
            onClick={() => { load(); setInventoryRevision(value => value + 1); }}
            className="rounded-md bg-white/10 px-3 py-1 text-xs font-medium text-white/80 transition-colors hover:bg-white/20"
          >
            Reload
          </button>
          <button
            onClick={() => setRefreshOpen(true)}
            aria-haspopup="dialog"
            className="rounded-md bg-[#8ab4f8] px-3 py-1 text-xs font-semibold text-[#0b1020] transition-colors hover:bg-[#aecbfa]"
          >
            {busy ? 'Refreshing…' : 'Refresh'}
          </button>
        </span>
      </header>

      <nav aria-label="Odds views" className="flex flex-none gap-1 border-b border-white/10 px-4 py-2">
        {([['board', 'EV & Arb'], ['markets', 'All markets'], ['coverage', 'Coverage']] as const).map(([key,label]) =>
          <button key={key} onClick={() => setView(key)} aria-current={view === key ? 'page' : undefined}
            className={`rounded-lg px-4 py-2 text-sm font-medium ${view === key ? 'bg-[#8ab4f8]/15 text-[#8ab4f8]' : 'text-white/50 hover:bg-white/5 hover:text-white'}`}>{label}</button>)}
      </nav>
      <main className="min-h-0 flex-1">
        {view !== 'board' ? <OddsInventory key={inventoryRevision} coverage={view === 'coverage'} /> : <>
        {state.kind === 'ready' ? (
          <iframe
            title="Odds board"
            srcDoc={state.html}
            sandbox="allow-scripts"
            className="h-full w-full border-0"
          />
        ) : (
          <div className="flex h-full items-center justify-center px-6">
            <p className="max-w-sm text-center text-sm leading-relaxed text-white/50">
              {state.kind === 'loading' && 'Loading the board…'}
              {state.kind === 'unconfigured' &&
                'This build is missing its Supabase URL or anon key, so the board cannot load.'}
              {state.kind === 'empty' &&
                'Nothing published yet. The scanner writes here after its next sweep.'}
              {state.kind === 'error' && `Could not reach the board (${state.message}).`}
            </p>
          </div>
        )}
        </>}
      </main>
      <dialog ref={dialog} onCancel={() => setRefreshOpen(false)}
        onClose={() => { setRefreshOpen(false); setPin(''); }}
        aria-labelledby="odds-refresh-title"
        className="w-[calc(100%_-_2rem)] max-w-sm rounded-xl border border-white/15 bg-[#171a21] p-5 text-white shadow-2xl backdrop:bg-black/70">
        <div className="mb-3 flex items-center justify-between gap-3">
          <h2 id="odds-refresh-title" className="text-lg font-semibold">Refresh odds</h2>
          <button type="button" onClick={() => setRefreshOpen(false)} aria-label="Close refresh"
            className="rounded px-2 py-1 text-white/60 hover:text-white">✕</button>
        </div>
        <p className="mb-4 text-sm leading-relaxed text-white/60">
          Direct books collect continuously for games starting within 72 hours. This rebuilds the board from the latest checked database prices.
          The request has a 60-second deadline, including queue time.
          Fresh, compatible markets produce provisional EV and arb estimates. These assume matching settlement across books.
          The board also updates automatically. Slow, blocked or unfinished sources appear as coverage gaps. No Odds API credits are used.
          All markets is a separate historical catalogue. Price refreshes are limited to once per minute.
        </p>
        <form onSubmit={event => { void requestRefresh(event); }}>
          <label htmlFor="odds-refresh-pin" className="mb-2 block text-sm font-medium">Refresh PIN</label>
          <input id="odds-refresh-pin" type="password" inputMode="numeric" autoComplete="off"
            minLength={6} maxLength={10} pattern="[0-9]{6,10}" required autoFocus disabled={busy}
            value={pin} onChange={event => setPin(event.target.value)}
            className="mb-3 w-full rounded-lg border border-white/20 bg-black/20 px-3 py-2 text-lg tracking-widest outline-none focus:border-[#8ab4f8] disabled:opacity-50" />
          <button type="submit" disabled={busy || !/^\d{6,10}$/.test(pin)}
            className="w-full rounded-lg bg-[#8ab4f8] px-4 py-2 text-sm font-semibold text-[#0b1020] disabled:opacity-40">
            {busy ? 'Refreshing…' : 'Refresh board'}
          </button>
        </form>
        <div aria-live="polite" className="mt-4 text-sm leading-relaxed text-white/70">
          {refreshError || refresh?.message || ''}
          {refresh?.state === 'complete' && typeof refresh.details?.credits_spent === 'number' && (
            <p className="mt-1 text-xs text-white/50">{refresh.details.credits_spent} Odds API credits used.</p>
          )}
          {refresh?.state === 'complete' && typeof refresh.details?.selections === 'number' && (
            <p className="mt-1 text-xs text-amber-100/70">{refresh.details.selections.toLocaleString()} selections captured · {refresh.details.edges ?? 0} provisional EV · {refresh.details.arbs ?? 0} provisional arb.</p>
          )}
          {!!refresh?.retry_after_seconds && (
            <p className="mt-1 text-xs text-white/50">Try again in {Math.ceil(refresh.retry_after_seconds / 60)} min.</p>
          )}
        </div>
      </dialog>
    </div>
  );
}
